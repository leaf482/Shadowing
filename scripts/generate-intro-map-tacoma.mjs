/**
 * Stitch OSM raster tiles into src/assets/intro-map-central-tacoma.png and write
 * src/data/introMapPreviewBounds.js so intro pins match the image (ODbL — attribution in UI).
 *
 *   node scripts/generate-intro-map-tacoma.mjs
 */
import { writeFile, mkdir } from "fs/promises";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import sharp from "sharp";
import { MAP_CENTER } from "../src/data/clinics.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const UA = "ShadowingIntroMap/1.0 (+https://github.com/)";

const ZOOM = 13;
/** 2×2 tiles around MAP_CENTER — ~central Tacoma at z13 */
const GRID = 2;

function lonLatToTileXY(lat, lon, z) {
  const n = 2 ** z;
  const x = ((lon + 180) / 360) * n;
  const latRad = (lat * Math.PI) / 180;
  const y =
    ((1 -
      Math.log(Math.tan(latRad) + 1 / Math.cos(latRad)) / Math.PI) /
      2) *
    n;
  return { x: Math.floor(x), y: Math.floor(y) };
}

function latNorthEdgeDeg(y, z) {
  const n = 2 ** z;
  return (Math.atan(Math.sinh(Math.PI * (1 - (2 * y) / n))) * 180) / Math.PI;
}

function lonWestEdgeDeg(x, z) {
  const n = 2 ** z;
  return (x / n) * 360 - 180;
}

async function fetchTile(z, x, y) {
  const url = `https://tile.openstreetmap.org/${z}/${x}/${y}.png`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${url} → ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

async function main() {
  const anchor = lonLatToTileXY(MAP_CENTER.lat, MAP_CENTER.lng, ZOOM);
  const x0 = anchor.x - (GRID - 1);
  const y0 = anchor.y - (GRID - 1);

  const composite = [];
  for (let row = 0; row < GRID; row++) {
    for (let col = 0; col < GRID; col++) {
      const tx = x0 + col;
      const ty = y0 + row;
      const buf = await fetchTile(ZOOM, tx, ty);
      composite.push({
        input: buf,
        left: col * 256,
        top: row * 256
      });
    }
  }

  const width = GRID * 256;
  const height = GRID * 256;
  const pngPath = join(repoRoot, "src", "assets", "intro-map-central-tacoma.png");
  await mkdir(dirname(pngPath), { recursive: true });

  await sharp({
    create: {
      width,
      height,
      channels: 3,
      background: { r: 232, g: 236, b: 241 }
    }
  })
    .composite(composite)
    .png()
    .toFile(pngPath);

  const west = lonWestEdgeDeg(x0, ZOOM);
  const east = lonWestEdgeDeg(x0 + GRID, ZOOM);
  const north = latNorthEdgeDeg(y0, ZOOM);
  const south = latNorthEdgeDeg(y0 + GRID, ZOOM);

  const boundsPath = join(repoRoot, "src", "data", "introMapPreviewBounds.js");
  const boundsSrc = `// Generated by scripts/generate-intro-map-tacoma.mjs — run \`node scripts/generate-intro-map-tacoma.mjs\` after changing tile grid.
export const INTRO_MAP_BOUNDS = {
  minLat: ${south},
  maxLat: ${north},
  minLng: ${west},
  maxLng: ${east}
};
`;
  await writeFile(boundsPath, boundsSrc, "utf8");

  console.log(`Wrote ${pngPath} (${width}×${height})`);
  console.log(`Wrote ${boundsPath}`);
  console.log(
    `Bounds: lat ${south.toFixed(5)} … ${north.toFixed(5)}, lng ${west.toFixed(5)} … ${east.toFixed(5)}`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
